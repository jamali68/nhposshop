import fs from 'fs';
import path from 'path';

// Source paths of the user-provided official NH POS logo files
const OFFICIAL_512_SRC = path.join(process.cwd(), 'public/assets/aistudio/1792729704800__1__bf19ca55.png');
const OFFICIAL_192_SRC = path.join(process.cwd(), 'public/assets/aistudio/1792729704800_2bd436ee.png');

export function generatePWAAssets() {
  console.log('Distributing official NH POS Logo assets across PWA directories...');

  if (!fs.existsSync(OFFICIAL_512_SRC)) {
    console.error('Error: Official 512x512 logo not found at', OFFICIAL_512_SRC);
    return;
  }

  const png512Buffer = fs.readFileSync(OFFICIAL_512_SRC);
  const png192Buffer = fs.existsSync(OFFICIAL_192_SRC)
    ? fs.readFileSync(OFFICIAL_192_SRC)
    : png512Buffer;

  const base64Logo = png512Buffer.toString('base64');
  const officialLogoSvg = `<svg width="512" height="512" viewBox="0 0 512 512" xmlns="http://www.w3.org/2000/svg">
  <image href="data:image/png;base64,${base64Logo}" width="512" height="512" />
</svg>`;

  const targets = ['public', 'dist', 'docs'];

  targets.forEach((dir) => {
    if (!fs.existsSync(dir)) return;

    // 1. Write official icons in base directory
    fs.writeFileSync(path.join(dir, 'icon-512.png'), png512Buffer);
    fs.writeFileSync(path.join(dir, 'icon-192.png'), png192Buffer);
    fs.writeFileSync(path.join(dir, 'apple-touch-icon.png'), png192Buffer);
    fs.writeFileSync(path.join(dir, 'icon.png'), png512Buffer);
    fs.writeFileSync(path.join(dir, 'icon1.png'), png512Buffer);
    fs.writeFileSync(path.join(dir, 'icon.svg'), officialLogoSvg, 'utf8');

    // 2. Write official icons in assets subdirectory
    const assetsDir = path.join(dir, 'assets');
    if (fs.existsSync(assetsDir)) {
      fs.writeFileSync(path.join(assetsDir, 'icon-512.png'), png512Buffer);
      fs.writeFileSync(path.join(assetsDir, 'icon-192.png'), png192Buffer);
      fs.writeFileSync(path.join(assetsDir, 'apple-touch-icon.png'), png192Buffer);
      fs.writeFileSync(path.join(assetsDir, 'icon.png'), png512Buffer);
      fs.writeFileSync(path.join(assetsDir, 'icon1.png'), png512Buffer);
      fs.writeFileSync(path.join(assetsDir, 'icon.svg'), officialLogoSvg, 'utf8');

      // Check for hashed icons generated by Vite bundler (e.g. icon-192-*.png, icon-512-*.png) and replace them
      const files = fs.readdirSync(assetsDir);
      files.forEach((f) => {
        if (f.startsWith('icon-192') && f.endsWith('.png')) {
          fs.writeFileSync(path.join(assetsDir, f), png192Buffer);
        }
        if (f.startsWith('icon-512') && f.endsWith('.png')) {
          fs.writeFileSync(path.join(assetsDir, f), png512Buffer);
        }
      });
    }

    console.log(`✅ Official NH POS Logo copied and active in: ${dir}`);
  });
}

// Run immediately if executed directly
if (process.argv[1]?.endsWith('generate-icons.js')) {
  generatePWAAssets();
}
